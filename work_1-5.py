# ---------------------------------------------------------------
# ЗАДАЧА 1. Приветствие с анализом имени
# ----------------------------------------------------------------
# Условие:
#     Запросить у пользователя имя.
#     Вывести приветствие + длину имени + имя заглавными буквами.
#     Если имя пустое — вывести "Имя не введено".
#
# Данные:
#     Ввод:  Аня       -> Вывод: Привет, Аня! Длина имени: 3. АНЯ
#     Ввод:  Александр -> Вывод: Привет, Александр! Длина имени: 9. АЛЕКСАНДР
#     Ввод:  (пусто)   -> Вывод: Имя не введено

name = input().strip()
if not name:
    print("Имя не введено")
else:
    print(f"Привет, {name}! Длина имени: {len(name)}. {name.upper()}")


# ----------------------------------------------------------------
# ЗАДАЧА 2. Анализ двух чисел
# ----------------------------------------------------------------
# Условие:
#     Запросить два числа a и b. Вывести сумму, разность, произведение,
#     частное (a/b) и остаток от деления (a%b).
#     Если b == 0 — вместо частного и остатка вывести "деление на ноль".
#
# Данные:
#     Ввод:  10, 3
#     Вывод: сумма=13, разность=7, произведение=30, частное=3.33, остаток=1
#
#     Ввод:  7, 0
#     Вывод: сумма=7, разность=7, произведение=0, деление на ноль

a = int(input())
b = int(input())
if b == 0:
    print(f"сумма={a + b}, разность={a - b}, произведение={a * b}, деление на ноль")
else:
    print(f"сумма={a + b}, разность={a - b}, произведение={a * b}, частное={a / b:.2f}, остаток={a % b}")


# ----------------------------------------------------------------
# ЗАДАЧА 3. Классификация числа
# ----------------------------------------------------------------
# Условие:
#     Запросить число. Вывести:
#         - "чётное" или "нечётное"
#         - "положительное", "отрицательное" или "ноль"
#         - кратно ли оно 5 (да/нет)
#     Всё в одной строке через запятую.
#
# Данные:
#     Ввод:  10    -> Вывод: чётное, положительное, кратно 5: да
#     Ввод:  -7    -> Вывод: нечётное, отрицательное, кратно 5: нет
#     Ввод:  0     -> Вывод: чётное, ноль, кратно 5: да
#     Ввод:  15    -> Вывод: нечётное, положительное, кратно 5: да

n = int(input())
parity = "чётное" if n % 2 == 0 else "нечётное"
if n > 0:
    sign = "положительное"
elif n < 0:
    sign = "отрицательное"
else:
    sign = "ноль"
mult5 = "да" if n % 5 == 0 else "нет"
print(f"{parity}, {sign}, кратно 5: {mult5}")


# ----------------------------------------------------------------
# ЗАДАЧА 4. Упорядочить три числа
# ----------------------------------------------------------------
# Условие:
#     Запросить три числа и вывести их:
#         - по возрастанию
#         - по убыванию
#         - максимум и минимум
#
# Данные:
#     Ввод:  5, 12, 9
#     Вывод: по возрастанию: 5 9 12
#            по убыванию: 12 9 5
#            мин=5, макс=12
#
#     Ввод:  -1, -5, -3
#     Вывод: по возрастанию: -5 -3 -1
#            по убыванию: -1 -3 -5
#            мин=-5, макс=-1

nums = [int(input()) for _ in range(3)]
asc = sorted(nums)
desc = sorted(nums, reverse=True)
print("по возрастанию:", *asc)
print("по убыванию:", *desc)
print(f"мин={min(nums)}, макс={max(nums)}")


# ----------------------------------------------------------------
# ЗАДАЧА 5. Квадратная таблица умножения
# ----------------------------------------------------------------
# Условие:
#     Запросить N и вывести таблицу умножения N×N
#     (строки от 1 до N, столбцы от 1 до N), выровненную по ширине.
#
# Данные:
#     Ввод:  3
#     Вывод: 1  2  3
#            2  4  6
#            3  6  9
#
#     Ввод:  5
#     Вывод: 1  2  3  4  5
#            2  4  6  8  10
#            3  6  9  12 15
#            4  8  12 16 20
#            5  10 15 20 25

n = int(input())
width = len(str(n * n))
for i in range(1, n + 1):
    print(" ".join(f"{i * j:<{width}}" for j in range(1, n + 1)).rstrip())
